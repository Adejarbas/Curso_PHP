<?php

    $x = 0;

    switch($x) {
        
        case 0:
            echo "X é igual a 0 <br>";
            break;
        case 1:
            echo "X é igual a 1 <br>";
            break;
        case 2:
            echo "X é igual a 2 <br>";
            break;
        default:
            echo "X não é igual a 0, 1 ou 2 <br>";
            break;   
    }


